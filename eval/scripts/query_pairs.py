"""Query sensitivity: pairs of queries on the same recording whose targets do not overlap (max IoU < 0.1).
A pair is solved if each prediction overlaps its own target more than the other query's target.
Uses the stored predictions; writes paper_v2/Tables/query_pairs.tex.
usage (from experiments/eval): ../../envs/eval/bin/python ../../eval/scripts/query_pairs.py"""
import sys, os, itertools, collections
import numpy as np
sys.path.insert(0, "experiments/eval")
import paper_tables as P
from agl_eval.metrics import max_iou


def iou(a, b):
    i = max(0, min(a[1], b[1]) - max(a[0], b[0])); u = max(a[1], b[1]) - min(a[0], b[0])
    return i / u if u > 0 else 0


def pairs(gt):
    by = collections.defaultdict(list)
    for i, g in enumerate(gt):
        by[g["vid"]].append(i)
    return [(a, b) for ix in by.values() for a, b in itertools.combinations(ix, 2)
            if max(iou(x, y) for x in gt[a]["gt"] for y in gt[b]["gt"]) < 0.1]


def solved(exp, bench, gt, pr):
    out = []
    for k in (0, 1, 2):
        fs = [f"{P.R}/{exp}/{k}/preds/{t}/{bench}_original.jsonl" for t in ("tacos", "default")]
        fs = [f for f in fs if os.path.exists(f)]
        if not fs:
            continue
        recs = P.T.build_records(gt, P.T.load_preds([fs[0]]))
        ok = 0
        for a, b in pr:
            pa, pb = recs[a]["pred"], recs[b]["pred"]
            if pa and pb and max_iou(pa, gt[a]["gt"]) > max_iou(pa, gt[b]["gt"]) and max_iou(pb, gt[b]["gt"]) > max_iou(pb, gt[a]["gt"]):
                ok += 1
        out.append(100 * ok / len(pr))
    return out


BENCH = [("clotho_moment", P.GT[("clotho_moment", "original")]), ("unav100", P.GT[("unav100", "original")]), ("tacos", P.TACOS_GT)]
ROWS = [("AudioGround ($\\rho_0=22\\%$, ATE$_h$)", "E0_main"), ("AudioGround ($\\rho_0=0\\%$, ATE$_l$)", "E1L_fi_ts_learned"),
        ("\\quad + no gap", "E4La_nogap"), ("\\quad + crossfade", "E4La_crossfade"), ("\\quad + overlap", "E4La_overlap"),
        ("\\quad + background mix", "E4La_bgmix")]
PR = {b: pairs(g) for b, g in BENCH}
lines = [r"% Generated by eval/scripts/query_pairs.py -- do not edit by hand.", r"\begin{table}[t]", r"\centering", r"\scriptsize",
         r"\caption{\rev{Query sensitivity, measured as the share of solved query pairs in \% (mean and standard deviation over three seeds on 1,201, 22, and 6,809 pairs); bold marks the best per column, and a standard deviation of 0.0 is below 0.05.}}",
         r"\label{tab:query_pairs}", r"\begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lccc@{}}", r"\toprule",
         r"Model & Clotho-Moment & UnAV-100 & TACOS \\", r"\midrule"]
vals = {lab: [solved(exp, b, g, PR[b]) for b, g in BENCH] for lab, exp in ROWS}
best = [max(np.mean(vals[lab][k]) for lab, _ in ROWS if len(vals[lab][k]) == 3) for k in range(len(BENCH))]
for lab, exp in ROWS:
    cells = []
    for k, v in enumerate(vals[lab]):
        if len(v) != 3:
            cells.append("--"); continue
        m = f"{np.mean(v):.1f}"
        cells.append((f"\\textbf{{{m}}}" if abs(np.mean(v) - best[k]) < 1e-9 else m) + f"$_{{\\pm{np.std(v, ddof=1):.1f}}}$")
    print(lab, cells)
    lines.append(f"{lab} & " + " & ".join(cells) + r" \\")
    if exp == "E1L_fi_ts_learned":
        lines.append(r"\midrule")
lines += [r"\bottomrule", r"\end{tabular*}", r"\end{table}"]
open("results/tables/query_pairs.tex", "w").write("\n".join(lines) + "\n")
